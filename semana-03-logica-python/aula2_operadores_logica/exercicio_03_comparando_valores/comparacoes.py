nota_joao = 7.5
nota_maria = 8.2

print(nota_joao > nota_maria)   # João tem nota MAIOR que Maria? Não
print(nota_joao < nota_maria)   # João tem nota MENOR que Maria? Sim
print(nota_joao == nota_maria)  # As notas são IGUAIS? Não
print(nota_joao != nota_maria)  # As notas são DIFERENTES? Sim


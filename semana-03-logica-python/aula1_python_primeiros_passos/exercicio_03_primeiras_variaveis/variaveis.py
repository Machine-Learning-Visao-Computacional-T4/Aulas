# Primeiras variáveis: três informações sobre você
seu_nome = "Ana"
sua_cidade = "Florianópolis"
seu_ano_nascimento = 2000

# print() juntando as 3 variáveis em uma frase
print("Eu sou", seu_nome, "de", sua_cidade, "e nasci em", seu_ano_nascimento)

# type() mostra o tipo de cada variável
print(type(seu_nome))
print(type(seu_ano_nascimento))

